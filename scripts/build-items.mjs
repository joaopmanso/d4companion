// Builds public/data/items.json: one catalog of every item the synced data knows, across all classes.
// Uniques and mythics (with type, slot and affix pool), aspects, charms, seals, runes and gems.
// The screenshot reader identifies an item by name from this list, then takes its type and slot from here.
// Run by scripts/fetch-guides.mjs after each sync, or on its own with `npm run items`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { slotFromType, SLOT } from "../src/data/slots.js";

const typeLine = (tip) => String(tip || "").split("\n")[1] || "";
// The scraper sometimes stored the socketed gem's tooltip ("Soul Splinter") instead of the item's own.
const isUniqueTip = (tip) => /^(mythic\s+)?unique\b/i.test(typeLine(tip));
const isAspectTip = (tip, name) => String(tip || "").split("\n")[0] === name && !/soul splinter/i.test(typeLine(tip));

export function buildItems(dataDir) {
  const read = (f) => JSON.parse(readFileSync(join(dataDir, f), "utf8"));
  const uniques = new Map(), aspects = new Map(), charms = {}, seals = {}, runes = {}, gems = {};
  const addUnique = (name, it, className, slotName) => {
    const u = uniques.get(name) || { name, rarity: "unique", kind: it.kind, type: "", slot: null, tip: "", art: it.art || "", classes: [] };
    if (it.kind === "mythic" || it.rarity === "mythic" || /mythic/i.test(typeLine(it.tip))) u.rarity = "mythic";
    if (!u.tip && isUniqueTip(it.tip)) {
      u.tip = it.tip;
      u.type = typeLine(it.tip).replace(/^(mythic\s+)?unique\s+/i, "").trim();
    }
    u.slot ||= slotFromType(u.type) || slotFromType(slotName);
    if (className && !u.classes.includes(className)) u.classes.push(className);
    uniques.set(name, u);
  };
  for (const f of readdirSync(dataDir).filter((f) => /^class-.+\.json$/.test(f)).sort()) {
    const { className, catalog = {} } = read(f);
    for (const [name, it] of Object.entries(catalog.items || {})) {
      if (it.kind === "aspect" || it.kind === "legendary") {
        if (!aspects.has(name) && isAspectTip(it.tip, name)) aspects.set(name, { name, tip: it.tip, classes: [] });
        aspects.get(name)?.classes.push(className);
      } else addUnique(name, it, className, it.slot);
    }
    for (const [name, c] of Object.entries(catalog.charms || {})) charms[name] ||= c;
    for (const [name, s] of Object.entries(catalog.seals || {})) seals[name] ||= s;
    for (const [name, r] of Object.entries(catalog.runes || {})) runes[name] ||= r;
    for (const [name, g] of Object.entries(catalog.gems || {})) gems[name] ||= g;
  }
  // Guides carry the same items with the slot they're worn in, sometimes with the right tooltip where the class file has the wrong one.
  for (const f of readdirSync(join(dataDir, "guides")).sort()) {
    const g = read(join("guides", f));
    for (const s of Object.values(g.slots || {})) {
      if (["unique", "mythic", "runeword"].includes(s.item?.kind)) addUnique(s.item.name, s.item, g.className, s.name);
    }
  }
  const byName = (a, b) => a.name.localeCompare(b.name);
  for (const u of uniques.values()) {
    if (!u.slot && !u.tip) uniques.delete(u.name); // a guide's placeholder ("Offhand"), not an item
    else u.type ||= u.slot === "ring" ? "Ring" : SLOT[u.slot]?.noun || "";
  }
  return {
    note: "Generated by scripts/build-items.mjs from the class files and guides. Don't edit by hand.",
    uniques: [...uniques.values()].sort(byName),
    aspects: [...aspects.values()].sort(byName),
    charms, seals, runes, gems,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dataDir = new URL("../public/data/", import.meta.url).pathname;
  const items = buildItems(dataDir);
  writeFileSync(join(dataDir, "items.json"), JSON.stringify(items, null, 1) + "\n");
  const noTip = items.uniques.filter((u) => !u.tip).map((u) => u.name);
  console.log(`items.json: ${items.uniques.length} uniques/mythics (${noTip.length} without a clean tooltip), ${items.aspects.length} aspects, ${Object.keys(items.charms).length} charms, ${Object.keys(items.seals).length} seals, ${Object.keys(items.runes).length} runes, ${Object.keys(items.gems).length} gems`);
  if (noTip.length) console.log(`no clean tooltip: ${noTip.join(", ")}`);
}
